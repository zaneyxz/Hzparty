import type { TicketReservation } from '../types/hz';

export const TICKET_CODE_REGEX = /^HZ-[A-Z0-9]{6}$/;

export interface ParsedTicketQr {
  valid: boolean;
  ticketCode: string | null;
  qrHolderHint: string | null;
  sourceFormat: 'hzparty-qr' | 'direct-code' | 'unknown';
  rawValue: string;
}

export type TicketScanOutcome =
  | 'valid'
  | 'already-used'
  | 'invalid'
  | 'unpaid'
  | 'error';

export interface TicketScanResult {
  id: string;
  outcome: TicketScanOutcome;
  scannedAt: string;
  rawInput: string;
  ticketCode: string | null;
  ticket?: TicketReservation;
  validatedAt?: string;
  syncedFromMp?: boolean;
  message: string;
}

/**
 * Parses QR payloads generated by the existing HZ PARTY ticket pass
 * (`HZPARTY|HZ-XXXXXX|Nome`) as well as direct ticket codes (`HZ-XXXXXX`).
 * Never trusts holder names embedded in the QR payload — only extracts the
 * strict ticket code identifier for real-time Firestore verification.
 */
export function parseTicketQrPayload(rawValue: string): ParsedTicketQr {
  const trimmed = rawValue.trim();
  if (!trimmed || trimmed.length > 260) {
    return {
      valid: false,
      ticketCode: null,
      qrHolderHint: null,
      sourceFormat: 'unknown',
      rawValue: trimmed.slice(0, 120),
    };
  }

  // Exact format generated by MyTicketPage: HZPARTY|HZ-XXXXXX|Holder Name
  if (trimmed.includes('|')) {
    const parts = trimmed.split('|').map((part) => part.trim());
    const prefix = (parts[0] ?? '').toUpperCase();
    const candidateCode = (parts[1] ?? '').toUpperCase();
    if (prefix === 'HZPARTY' && TICKET_CODE_REGEX.test(candidateCode)) {
      return {
        valid: true,
        ticketCode: candidateCode,
        qrHolderHint: parts[2] ? parts[2].slice(0, 120) : null,
        sourceFormat: 'hzparty-qr',
        rawValue: trimmed,
      };
    }

    return {
      valid: false,
      ticketCode: null,
      qrHolderHint: null,
      sourceFormat: 'unknown',
      rawValue: trimmed.slice(0, 120),
    };
  }

  // Direct ticket code fallback (e.g. HZ-AB12CD)
  const upper = trimmed.toUpperCase();
  if (TICKET_CODE_REGEX.test(upper)) {
    return {
      valid: true,
      ticketCode: upper,
      qrHolderHint: null,
      sourceFormat: 'direct-code',
      rawValue: trimmed,
    };
  }

  return {
    valid: false,
    ticketCode: null,
    qrHolderHint: null,
    sourceFormat: 'unknown',
    rawValue: trimmed.slice(0, 120),
  };
}

/**
 * Formats date and time in Brazilian format fitting Firestore's 40-char limit
 * for `validatedAtLabel` (e.g. "12/12/2026 às 23:14:08").
 */
export function formatValidationDateTime(date: Date = new Date()): string {
  const dd = String(date.getDate()).padStart(2, '0');
  const mm = String(date.getMonth() + 1).padStart(2, '0');
  const yyyy = String(date.getFullYear());
  const hh = String(date.getHours()).padStart(2, '0');
  const min = String(date.getMinutes()).padStart(2, '0');
  const sec = String(date.getSeconds()).padStart(2, '0');
  return `${dd}/${mm}/${yyyy} às ${hh}:${min}:${sec}`;
}

/**
 * Prevents duplicate scans of the exact same QR held in front of the camera
 * within the cooldown window, while letting a different ticket scan immediately.
 */
export function shouldSkipDuplicateScan(
  lastScan: { raw: string; atMs: number } | null,
  nextRaw: string,
  nowMs: number,
  cooldownMs = 3500
): boolean {
  if (!lastScan) return false;
  if (lastScan.raw.trim().toUpperCase() !== nextRaw.trim().toUpperCase()) {
    return false;
  }
  return nowMs - lastScan.atMs < cooldownMs;
}
