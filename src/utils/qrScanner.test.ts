import test from 'node:test';
import assert from 'node:assert/strict';
import QRCode from 'qrcode';
import jsQR from 'jsqr';
import {
  formatValidationDateTime,
  parseTicketQrPayload,
  shouldSkipDuplicateScan,
} from './qrScanner';

test('parses exact HZPARTY|HZ-XXXXXX|Name format generated by MyTicketPage', () => {
  const parsed = parseTicketQrPayload('HZPARTY|HZ-AB12CD|Mariana Costa');
  assert.equal(parsed.valid, true);
  assert.equal(parsed.ticketCode, 'HZ-AB12CD');
  assert.equal(parsed.qrHolderHint, 'Mariana Costa');
  assert.equal(parsed.sourceFormat, 'hzparty-qr');
});

test('normalizes lowercase and extra whitespace in QR payload and direct ticket code', () => {
  const fromQr = parseTicketQrPayload('  hzparty | hz-9k4m2p | João Silva  ');
  assert.equal(fromQr.valid, true);
  assert.equal(fromQr.ticketCode, 'HZ-9K4M2P');
  assert.equal(fromQr.sourceFormat, 'hzparty-qr');

  const direct = parseTicketQrPayload('  hz-1a2b3c ');
  assert.equal(direct.valid, true);
  assert.equal(direct.ticketCode, 'HZ-1A2B3C');
  assert.equal(direct.sourceFormat, 'direct-code');
});

test('rejects invalid QR strings, Pix payloads, guest-list protocols, and URLs', () => {
  const invalidSamples = [
    '',
    '   ',
    'HZ-123',
    'HZPL-AB12CD',
    'OTHER|HZ-AB12CD|Test',
    'HZPARTY|INVALID|Test',
    '00020126580014br.gov.bcb.pix0136fake-pix-code',
    'https://example.com/HZ-AB12CD',
    'HZ-AB12CD-EXTRA',
  ];

  for (const sample of invalidSamples) {
    const parsed = parseTicketQrPayload(sample);
    assert.equal(parsed.valid, false, `Expected "${sample}" to be rejected`);
    assert.equal(parsed.ticketCode, null);
  }
});

test('formats validation date/time cleanly within Firestore 40-char constraint', () => {
  const sampleDate = new Date(2026, 11, 12, 23, 5, 9);
  const formatted = formatValidationDateTime(sampleDate);
  assert.equal(formatted, '12/12/2026 às 23:05:09');
  assert.ok(formatted.length <= 40);
});

test('suppresses repeated camera reads of same QR inside cooldown but allows different QR immediately', () => {
  const last = { raw: 'HZPARTY|HZ-AB12CD|Ana', atMs: 10000 };
  assert.equal(shouldSkipDuplicateScan(last, 'HZPARTY|HZ-AB12CD|Ana', 11500, 3500), true);
  assert.equal(shouldSkipDuplicateScan(last, 'HZPARTY|HZ-AB12CD|Ana', 14000, 3500), false);
  assert.equal(shouldSkipDuplicateScan(last, 'HZPARTY|HZ-XY98ZW|Pedro', 10200, 3500), false);
  assert.equal(shouldSkipDuplicateScan(null, 'HZPARTY|HZ-AB12CD|Ana', 10000, 3500), false);
});

test('end-to-end ISO QR encode (with crimson finder eyes) decodes cleanly with jsQR', () => {
  const payload = 'HZPARTY|HZ-7F4K9Q|Lucas Oliveira';
  const qr = QRCode.create(payload, { errorCorrectionLevel: 'M' });
  const moduleCount = qr.modules.size;
  const quietZone = 4;
  const scale = 6;
  const imgSize = (moduleCount + quietZone * 2) * scale;
  const rgba = new Uint8ClampedArray(imgSize * imgSize * 4);
  rgba.fill(255); // White background

  for (let r = 0; r < moduleCount; r += 1) {
    for (let c = 0; c < moduleCount; c += 1) {
      if (!qr.modules.get(r, c)) continue;
      const isCenterEye =
        (r >= 2 && r <= 4 && c >= 2 && c <= 4) ||
        (r >= 2 && r <= 4 && c >= moduleCount - 5 && c <= moduleCount - 3) ||
        (r >= moduleCount - 5 && r <= moduleCount - 3 && c >= 2 && c <= 4);

      const red = isCenterEye ? 220 : 9;
      const green = isCenterEye ? 20 : 9;
      const blue = isCenterEye ? 60 : 11;

      for (let dy = 0; dy < scale; dy += 1) {
        for (let dx = 0; dx < scale; dx += 1) {
          const x = (c + quietZone) * scale + dx;
          const y = (r + quietZone) * scale + dy;
          const idx = (y * imgSize + x) * 4;
          rgba[idx] = red;
          rgba[idx + 1] = green;
          rgba[idx + 2] = blue;
          rgba[idx + 3] = 255;
        }
      }
    }
  }

  const decoded = jsQR(rgba, imgSize, imgSize, { inversionAttempts: 'dontInvert' });
  assert.ok(decoded, 'jsQR must decode the rendered HZ PARTY QR code');
  assert.equal(decoded.data, payload);

  const parsed = parseTicketQrPayload(decoded.data);
  assert.equal(parsed.valid, true);
  assert.equal(parsed.ticketCode, 'HZ-7F4K9Q');
});
